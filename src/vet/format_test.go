func TestRunGofmtSkipsGeneratedFiles(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "generated.go")
	content := "// Code generated by test. DO NOT EDIT.\n\npackage main\nfunc f(){println(\"generated\")}\n"
	writeFile(t, path, content)
	chdir(t, dir)

	ed := NewEditor(false)
	changed, err := RunGofmt(ed)
	require.NoError(t, err)
	assert.False(t, changed)
	require.NoError(t, ed.Err())

	changed, err = RunGofmt(NewEditor(true))
	require.NoError(t, err)
	assert.False(t, changed)

	got, err := os.ReadFile(path)
	require.NoError(t, err)
	assert.Equal(t, content, string(got))
}

func TestRunGofmtSkipsUnparseable(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "broken.go"), "package main\nfunc ({\n")
	chdir(t, dir)

	// Should not return an error for parse failures — go vet covers those.
	ed := NewEditor(false)
	_, err := RunGofmt(ed)
	require.NoError(t, err)
	require.NoError(t, ed.Err())
}

